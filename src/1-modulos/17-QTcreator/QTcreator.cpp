QTcreator::QTcreator (ComunicacionAsincronica *uart)
{
	m_uart = uart;
}

void QTcreator::EnviarMenu(uint8_t opcion)
{

	m_trama[0] = '#';

	m_trama[1] = 'M';

	m_trama[2] = opcion + '0';

	m_trama[3] = '$';

	m_uart->Transmit( m_trama , 4 ); //manda los caracteres para que qtcreator los reciba

}
